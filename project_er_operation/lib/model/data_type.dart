import 'enums.dart';

/// 複合型の項目(6.3-2)。
class TypeField {
  TypeField({
    this.name = '',
    this.typeId = 'integer',
    this.length,
    this.precision,
    this.scale,
  });
  String name;
  String typeId;
  int? length;
  int? precision;
  int? scale;

  TypeField copy() =>
      TypeField(name: name, typeId: typeId, length: length, precision: precision, scale: scale);
}

/// 型の定義(6.3)。モデルに保存する。
class DataType {
  DataType({
    required this.id,
    required this.displayName,
    this.paramKind = ParamKind.none,
    this.defaultLength,
    this.defaultPrecision,
    this.defaultScale,
    this.category = TypeCategory.string,
    Map<DbKind, String>? physical,
    this.isStandard = false,
    this.kind = TypeKind.scalar,
    List<TypeField>? fields,
    List<String>? enumValues,
  })  : physical = physical ?? {},
        fields = fields ?? [],
        enumValues = enumValues ?? [];

  final String id;
  String displayName;
  ParamKind paramKind;
  int? defaultLength;
  int? defaultPrecision;
  int? defaultScale;
  TypeCategory category;

  /// 対象DBごとの物理名テンプレート。
  final Map<DbKind, String> physical;

  /// 標準型は削除できない(6.3-3)。IDが付録Cに含まれるかで判定する。
  final bool isStandard;

  /// 種別。ユーザー定義型(composite / enumeration)は、物理名テンプレートが型の名前になる。
  TypeKind kind;

  /// 複合型の項目(kind が composite のとき)。
  List<TypeField> fields;

  /// 列挙型の値(kind が enumeration のとき)。
  List<String> enumValues;

  bool get isUserDefined => kind != TypeKind.scalar;

  DataType copy() => DataType(
        id: id,
        displayName: displayName,
        paramKind: paramKind,
        defaultLength: defaultLength,
        defaultPrecision: defaultPrecision,
        defaultScale: defaultScale,
        category: category,
        physical: Map.of(physical),
        isStandard: isStandard,
        kind: kind,
        fields: fields.map((f) => f.copy()).toList(),
        enumValues: List.of(enumValues),
      );

  /// テンプレートをパラメータ展開した物理型名。テンプレート未定義はnull。
  String? expand(DbKind db, {int? length, int? precision, int? scale}) {
    final t = physical[db];
    if (t == null || t.isEmpty) return null;
    return t
        .replaceAll('{length}', '${length ?? defaultLength ?? ''}')
        .replaceAll('{precision}', '${precision ?? defaultPrecision ?? ''}')
        .replaceAll('{scale}', '${scale ?? defaultScale ?? ''}');
  }
}

DataType _t(
  String id,
  String name,
  TypeCategory cat,
  String pg,
  String my,
  String ms,
  String lite, {
  ParamKind kind = ParamKind.none,
  int? length,
  int? precision,
  int? scale,
}) =>
    DataType(
      id: id,
      displayName: name,
      category: cat,
      paramKind: kind,
      defaultLength: length,
      defaultPrecision: precision,
      defaultScale: scale,
      isStandard: true,
      physical: {
        DbKind.postgresql: pg,
        DbKind.mysql: my,
        DbKind.sqlserver: ms,
        DbKind.sqlite: lite,
      },
    );

/// 標準型(付録C)。毎回新しいインスタンスを返す。
List<DataType> standardTypes() {
  const n = TypeCategory.number;
  const s = TypeCategory.string;
  const d = TypeCategory.datetime;
  return [
    _t('smallint', 'smallint', n, 'smallint', 'SMALLINT', 'smallint', 'INTEGER'),
    _t('integer', 'integer', n, 'integer', 'INT', 'int', 'INTEGER'),
    _t('bigint', 'bigint', n, 'bigint', 'BIGINT', 'bigint', 'INTEGER'),
    _t('auto', 'auto(自動採番)', TypeCategory.auto,
        'integer GENERATED BY DEFAULT AS IDENTITY', 'INT AUTO_INCREMENT', 'int IDENTITY(1,1)', 'INTEGER'),
    _t('numeric', 'numeric(p,s)', n, 'numeric({precision},{scale})',
        'DECIMAL({precision},{scale})', 'decimal({precision},{scale})', 'NUMERIC',
        kind: ParamKind.precisionScale, precision: 18, scale: 2),
    _t('real', 'real', n, 'real', 'FLOAT', 'real', 'REAL'),
    _t('double', 'double', n, 'double precision', 'DOUBLE', 'float', 'REAL'),
    _t('boolean', 'boolean', TypeCategory.boolean, 'boolean', 'TINYINT(1)', 'bit', 'INTEGER'),
    _t('char', 'char(n)', s, 'char({length})', 'CHAR({length})', 'char({length})', 'TEXT',
        kind: ParamKind.length, length: 1),
    _t('varchar', 'varchar(n)', s, 'varchar({length})', 'VARCHAR({length})', 'varchar({length})', 'TEXT',
        kind: ParamKind.length, length: 255),
    _t('text', 'text', s, 'text', 'TEXT', 'varchar(max)', 'TEXT'),
    _t('date', 'date', d, 'date', 'DATE', 'date', 'TEXT'),
    _t('time', 'time', d, 'time', 'TIME', 'time', 'TEXT'),
    _t('timestamp', 'timestamp', d, 'timestamp', 'DATETIME', 'datetime2', 'TEXT'),
    _t('timestamptz', 'timestamptz', d, 'timestamptz', 'TIMESTAMP', 'datetimeoffset', 'TEXT'),
    _t('interval', 'interval', d, 'interval', 'TIME', 'time', 'TEXT'),
    _t('uuid', 'uuid', s, 'uuid', 'CHAR(36)', 'uniqueidentifier', 'TEXT'),
    _t('bytea', 'binary', TypeCategory.binary, 'bytea', 'BLOB', 'varbinary(max)', 'BLOB'),
    _t('json', 'json', TypeCategory.json, 'json', 'JSON', 'nvarchar(max)', 'TEXT'),
    _t('jsonb', 'jsonb', TypeCategory.json, 'jsonb', 'JSON', 'nvarchar(max)', 'TEXT'),
  ];
}

final Set<String> standardTypeIds = standardTypes().map((t) => t.id).toSet();
