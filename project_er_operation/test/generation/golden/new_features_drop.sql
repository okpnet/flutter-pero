SET search_path TO app, public;

CREATE SCHEMA IF NOT EXISTS app;

CREATE SCHEMA IF NOT EXISTS other;

DROP TYPE IF EXISTS status_t CASCADE;

CREATE TYPE status_t AS ENUM ('open', 'it''s closed');

DROP TYPE IF EXISTS point_t CASCADE;

CREATE TYPE point_t AS (x integer, label varchar(20));

DROP TABLE IF EXISTS app.node CASCADE;

CREATE TABLE app.node (
  id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  parent_id integer,
  name varchar(20) DEFAULT '',
  qty numeric(18,2),
  due date DEFAULT CURRENT_DATE + 30,
  state status_t,
  CONSTRAINT p_node_key PRIMARY KEY (id),
  CONSTRAINT node_ck1 CHECK (qty >= 0),
  CONSTRAINT node_state_ck CHECK (state <> 'closed' OR qty = 0)
);

ALTER TABLE app.node ADD CONSTRAINT node_uq UNIQUE NULLS NOT DISTINCT (name, qty);

CREATE FUNCTION count_nodes() RETURNS bigint AS $$ SELECT count(*) FROM node $$ LANGUAGE sql;

COMMENT ON FUNCTION count_nodes() IS 'ノード数';

DROP TABLE IF EXISTS other.other CASCADE;

CREATE TABLE other.other (
  id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  node_id integer,
  CONSTRAINT p_other_key PRIMARY KEY (id)
);

ALTER TABLE app.node ADD CONSTRAINT node_fk1 FOREIGN KEY (parent_id) REFERENCES app.node (id) ON DELETE SET NULL ON UPDATE NO ACTION DEFERRABLE INITIALLY DEFERRED;

ALTER TABLE other.other ADD CONSTRAINT other_fk1 FOREIGN KEY (id) REFERENCES app.node (id) ON DELETE NO ACTION ON UPDATE NO ACTION DEFERRABLE INITIALLY IMMEDIATE;

DROP VIEW IF EXISTS app.v_node;

CREATE VIEW app.v_node AS
SELECT id, name FROM app.node WHERE qty > 0;

COMMENT ON VIEW app.v_node IS 'ノードのビュー';

CREATE FUNCTION view_rows() RETURNS bigint AS $$ SELECT count(*) FROM app.v_node $$ LANGUAGE sql;

CREATE FUNCTION touch() RETURNS trigger AS $$ BEGIN RETURN NEW; END $$ LANGUAGE plpgsql;

COMMENT ON FUNCTION touch() IS '更新日時を設定する';

CREATE TRIGGER node_trg01 BEFORE INSERT OR UPDATE OF name, qty ON app.node FOR EACH ROW EXECUTE FUNCTION touch('80', 1);
